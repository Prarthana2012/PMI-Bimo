-- Data Product View: DP_CONSUMER_REGISTRATIONS_VW
CREATE VIEW IF NOT EXISTS {DB_NAME}.DP_BIMO.DP_CONSUMER_REGISTRATIONS_VW AS
SELECT TDE_CONSUMER_REGISTRATIONS_BK, WEEK_END_DATE, COUNTRY_CODE, REGION, CHANNEL_NAME, SUB_CHANNEL, STORE_TYPE, IQOS_TYPE, VEEV_TYPE, TOTAL_REGISTRATIONS
FROM {DB_NAME}.PRESENTATION.P_T_CONSUMER_REGISTRATIONS;
COMMENT ON VIEW {DB_NAME}.DP_BIMO.DP_CONSUMER_REGISTRATIONS_VW IS 'KAN-1 Consumer Registrations data product view';
ALTER VIEW {DB_NAME}.DP_BIMO.DP_CONSUMER_REGISTRATIONS_VW SET TAG {DB_NAME}.PMI_AGENT.BIONIC_PMI_POC = 'KAN-1';
